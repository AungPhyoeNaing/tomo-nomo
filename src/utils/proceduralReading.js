const GENERIC_NUMBER_SECOND = 'တစ်နေ့တာ အဖြစ်အပျက်တွေကို အပြန်အလှန် မျှဝေပြောပြရင်း တစ်ယောက်ရဲ့ စိတ်ဝင်စားမှုကို တစ်ယောက်က ပိုမိုနားလည်လာနိုင်ပါတယ်။';

function storyNumber(metrics) {
  return [metrics?.lifePathNumber, metrics?.destinyNumber].find(number => Number.isInteger(number) && Object.hasOwn(NUMBER_PROMPTS, number));
}

function numberPrompt(metrics, other, rank) {
  const number = storyNumber(metrics);
  if (!number) return rank ? GENERIC_NUMBER_SECOND : GENERIC_NUMBER;
  if (rank && number === storyNumber(other)) {
    return 'နှစ်ယောက်စလုံးရဲ့ ဂဏန်းသင်္ကေတချင်း တူညီနေတာကြောင့် စကားပြောဆိုတဲ့ စတိုင်ချင်း ဆင်တူနိုင်ပေမဲ့ ကိုယ်ပိုင်အတွေ့အကြုံချင်းတော့ ကွဲပြားနိုင်ပါတယ်။ တစ်ဖက်လူ ပြောပြီးတဲ့အခါ ကိုယ့်အတွက် ဖြစ်ခဲ့တဲ့ အတွေ့အကြုံလေးကို အပြန်အလှန် မျှဝေပြောပြနိုင်ပါတယ်။';
  }
  const label = number === metrics?.lifePathNumber ? 'ဘဝလမ်းကြောင်းဂဏန်း' : 'နာမည်ဂဏန်း';
  return rank
    ? `ဒီ${label}ရဲ့ အဓိပ္ပာယ်အရ ${NUMBER_PROMPTS[number]}`
    : `${label}ရဲ့ စရိုက်လက္ခဏာအရ ${NUMBER_PROMPTS[number]}`;
}

function chineseStory(first, second) {
  const animals = [first?.animal, second?.animal].map(animal => Object.hasOwn(ANIMAL_NAMES, animal) ? ANIMAL_NAMES[animal] : null);
  const animalStory = animals.every(Boolean)
    ? (first?.animal === second?.animal
      ? `နှစ်ယောက်စလုံး ${animals[0]}နှစ်ဖွားချင်း တူညီနေတာကြောင့် အကြိုက်နဲ့ စိတ်နေစိတ်ထား အတော်များများမှာ အလွယ်တကူ စည်းဝါးကိုက်တတ်ကြပါတယ်။`
      : `ရာသီခွင်ထဲက ${animals[0]}နဲ့ ${animals[1]}တို့ရဲ့ တွဲဖက်မှုဟာ အချင်းချင်း မတူတဲ့ စွမ်းရည်တွေကို ပေါင်းစပ်ပေးနိုင်တဲ့ ခရီးဖော်နှစ်ဦးလိုပါပဲ။`)
    : 'နှစ်ယောက်စလုံး စိတ်ကူးသစ်တွေကို အတူတကွ မျှဝေဖို့ နေရာကောင်းတစ်ခု ရှိနေပါတယ်။';
  const elements = [...new Set([first?.elementKey, second?.elementKey])].sort();
  const scenes = elements.filter(element => Object.hasOwn(CHINESE_ELEMENT_SCENES, element)).map(element => CHINESE_ELEMENT_SCENES[element]);
  return [animalStory, ...scenes].join(' ');
}

export function generateDeepProceduralReading(p1Name, p1Secret, p2Name, p2Secret, relType, mood, score) {
  const names = [normalizePersonName(p1Name), normalizePersonName(p2Name)];
  const modeKey = Object.hasOwn(MODES, relType) ? relType : 'Friends';
  const voiceKey = Object.hasOwn(VOICES, mood) ? mood : 'Sweet';
  const mode = MODES[modeKey], voice = VOICES[voiceKey];
  const metrics = [p1Secret, p2Secret];
  const keys = names.map((name, index) => personKey(name, metrics[index]));
  const pairSeed = JSON.stringify([modeKey, voiceKey, [...keys].sort()]);
  const topics = [...STORY_TOPICS].sort((a, b) => hashStory(pairSeed + a.id) - hashStory(pairSeed + b.id) || (a.id < b.id ? -1 : 1));
  const scoreStory = SCORE_STORIES.find(story => Number.isFinite(score) && score >= story.minimum) || SCORE_STORIES[1];
  const join = (...parts) => parts.filter(Boolean).join(' ');
  const headings = ['ပင်ကိုယ်စတိုင်', 'အဆင်မပြေတတ်တဲ့အချိန်', 'စကားပြောပုံ', 'စမ်းကြည့်နိုင်တဲ့အရာ'];

  const profile = (person, index) => {
    const name = names[index], other = names[1 - index];
    const otherMetrics = metrics[1 - index];
    // Assign openings by identity rather than input position, except when both
    // identities are exactly identical and still need two different profiles.
    const rank = keys[0] <= keys[1] ? index : 1 - index;
    const opening = voice.opening.slice(rank * 4, rank * 4 + 4);
    const symbol = Object.hasOwn(ELEMENTS, person?.westernElement) ? ELEMENTS[person.westernElement] : 'ကိုယ်နှစ်သက်တဲ့ အရာကို ပြန်လည်ရှာဖွေတတ်တဲ့ စိတ်နေစိတ်ထား';
    const knownSign = Object.hasOwn(SIGN_SCENES, person?.western);
    const sign = rank && knownSign && person.western === otherMetrics?.western
      ? 'နှစ်ယောက်စလုံး ရာသီခွင်ချင်း တူနေတာကြောင့် စိတ်နေစိတ်ထား အတော်များများကို အလိုလို သဘောပေါက်နိုင်ပေမဲ့၊ တစ်ယောက်ချင်းစီရဲ့ ကိုယ်ပိုင်အကြိုက်လေးတွေကိုလည်း သီးခြားတန်ဖိုးထားပေးတတ်ပါတယ်။'
      : knownSign ? SIGN_SCENES[person.western] : rank
        ? 'ကိုယ်နှစ်သက်တဲ့ အရာတစ်ခုကို ဘာကြောင့် ကြိုက်လဲဆိုတာ ရှင်းပြရင်း တစ်ဖက်လူ ဘယ်လိုမြင်လဲ မေးမြန်းနိုင်ပါတယ်။'
        : 'အစီအစဉ်တစ်ခုမှာ ကိုယ်ရွေးချင်တာကို ရှင်းပြပြီး တစ်ဖက်လူကိုလည်း လွတ်လပ်စွာ ရွေးချယ်ခွင့် ပေးနိုင်ပါတယ်။';
    const knownMoon = Object.hasOwn(MOON_PROMPTS, person?.moonElement);
    const moon = knownMoon
      ? (rank && person.moonElement === otherMetrics?.moonElement ? SHARED_MOON_PROMPTS : MOON_PROMPTS)[person.moonElement]
      : rank ? GENERIC_MOON_SECOND : GENERIC_MOON;
    const day = person?.dayIndex;
    const knownDay = Number.isInteger(day) && day >= 0 && day < DAY_NAMES.length;
    const ritual = rank && knownDay && day === otherMetrics?.dayIndex
      ? join(`မဟာဘုတ်ထဲက ${DAY_NAMES[day]}မွေးနေ့သင်္ကေတ နှစ်ယောက်တူနေပေမဲ့ မတူတဲ့ အခန်းကဏ္ဍကနေ အလှည့်ကျ စမ်းသပ်ကြည့်လို့ ရပါတယ်။`, topics[6].action)
      : knownDay ? DAY_RITUALS[day]
        : rank ? 'တစ်ခါတည်း အများကြီး မလုပ်ဘဲ အတူတူ စမ်းသပ်ပြီးမှ နောက်တစ်ဆင့်ကို ဖြည်းဖြည်းချင်း ရွေးချယ်နိုင်ပါတယ်။'
          : 'လုပ်ကြည့်ချင်တဲ့ အရာတစ်ခုအတွက် နှစ်ယောက်စလုံး အားလပ်တဲ့ အချိန်ကို ကြိုတင် ရွေးချယ်ထားနိုင်ပါတယ်။';

    const frameSentence = modeKey === 'Couple'
      ? `${name} အတွက် ${mode.frame}ကို စဉ်းစားတဲ့အခါ ${symbol}နဲ့ ချစ်ရသူကို နွေးထွေးစွာ ဂရုစိုက်တတ်တဲ့ သဘာဝရှိပါတယ်။`
      : `${name} အတွက် ${mode.frame}ကို စဉ်းစားတဲ့အခါ ${symbol}နဲ့ မိတ်ဆွေတွေအပေါ် ဖေးမကူညီတတ်တဲ့ သဘာဝရှိပါတယ်။`;

    const vulnerabilitySentence = modeKey === 'Couple'
      ? `${other} ရှေ့မှာ အမြဲတမ်း အဆင်ပြေနေသယောင် ဟန်ဆောင်မနေဘဲ ကိုယ့်ရဲ့ မွန်းကျပ်မှုနဲ့ လိုအပ်ချက်တွေကို ရိုးရိုးသားသား ဖွင့်ပြောပြလိုက်တာက စိတ်သက်သာရာကို ရစေပါတယ်။`
      : `${other} ရှေ့မှာ အမြဲတမ်း အဆင်ပြေနေသယောင် ဟန်ဆောင်မနေဘဲ ကိုယ်ရင်ဆိုင်နေရတဲ့ အခက်အခဲတွေကို ပွင့်ပွင့်လင်းလင်း မျှဝေတိုင်ပင်နိုင်ပါတယ်။`;

    const commSentence = modeKey === 'Couple'
      ? `${name} ပြောချင်တဲ့ အဓိပ္ပာယ်နဲ့ ${other} နားလည်လိုက်တဲ့ အရာ တိုက်ဆိုင်မှုရှိမရှိ သေချာလေး ပြန်လည်မေးမြန်းခြင်းက စကားဝိုင်းကို ပိုမိုကြည်လင်စေပါတယ်။`
      : `${name} ပြောချင်တဲ့ အဓိပ္ပာယ်နဲ့ ${other} နားလည်လိုက်တဲ့ အရာ တိုက်ဆိုင်မှုရှိမရှိ အချင်းချင်း ပြန်လည်ညှိနှိုင်းခြင်းက စကားဝိုင်းကို ပိုမိုကြည်လင်စေပါတယ်။`;

    const blocks = [
      join(opening[0], frameSentence, sign),
      join(opening[1], moon, vulnerabilitySentence),
      join(opening[2], numberPrompt(person, otherMetrics, rank), commSentence),
      join(opening[3], ritual, topics[rank].scene[modeKey])
    ];
    return blocks.map((block, i) => `[${headings[i]}]\n${block}`).join('\n\n');
  };

  const elementPair = [p1Secret?.westernElement, p2Secret?.westernElement].sort().join('/');
  const sharedRhythm = Object.hasOwn(ELEMENT_PAIR_STORIES, elementPair)
    ? ELEMENT_PAIR_STORIES[elementPair]
    : 'နှစ်ယောက်ရဲ့ အကြိုက်တူတဲ့ အရာလေးတွေနဲ့ မတူတဲ့ ရွေးချယ်မှုတွေကို အပြန်အလှန် လေးစားရင်း၊ အတူတကွ လုပ်ဆောင်မယ့် ကိစ္စတွေမှာ ဟန်ချက်ညီညီ ပူးပေါင်းဆောင်ရွက်နိုင်ကြပါတယ်။';

  const insightLead = modeKey === 'Couple'
    ? `${names[0]} နဲ့ ${names[1]} တို့ရဲ့ ချစ်သူဆက်ဆံရေးမှာ တစ်ယောက်နဲ့တစ်ယောက် ဆွဲဆောင်မှုရှိတဲ့ စည်းဝါးလေးတွေကို တွေ့မြင်နိုင်ပါတယ်။`
    : `${names[0]} နဲ့ ${names[1]} တို့ရဲ့ သူငယ်ချင်းဆက်ဆံရေးမှာ အချင်းချင်း စိတ်ချမ်းသာစေမယ့် ဆက်ဆံရေးစည်းဝါးတစ်ခု ရှိနေပါတယ်။`;

  const adviceLead = modeKey === 'Couple'
    ? `${names[0]} နဲ့ ${names[1]} တို့ရဲ့ ချစ်ခြင်းခရီးလမ်း ပိုမိုခိုင်မြဲလှပစေဖို့ နေ့စဉ်ဘဝမှာ အတူတကွ တည်ဆောက်သွားနိုင်တဲ့ အလေ့အကျင့်လေးတွေ ရှိပါတယ်။`
    : `${names[0]} နဲ့ ${names[1]} တို့ရဲ့ ခင်မင်မှုခရီးလမ်း ပိုမိုခိုင်မြဲလှပစေဖို့ နေ့စဉ်ဘဝမှာ အတူတကွ ထိန်းသိမ်းသွားနိုင်တဲ့ အလေ့အကျင့်ကောင်းလေးတွေ ရှိပါတယ်။`;

  return {
    chemistry_score: score,
    relationship_title: `${voice.title} ${mode.bond}နှစ်ဦး — ${topics[0].label}`,
    tomo_deep_reading_p1: profile(p1Secret, 0),
    tomo_deep_reading_p2: profile(p2Secret, 1),
    tomo_dynamic_insight: [
      join(insightLead, scoreStory.opening, sharedRhythm),
      join(voice.scenes[0], chineseStory(p1Secret, p2Secret), topics[2].scene[modeKey]),
      join(voice.scenes[1], topics[3].scene[modeKey], topics[4].question)
    ].join('\n\n'),
    tomo_strengths: topics.slice(5).map((topic, i) => {
      const custom = topic.strength?.[modeKey]?.[voiceKey];
      return custom || join(voice.strengths[i], topic.strength?.[modeKey]);
    }),
    tomo_challenges: topics.slice(5).map((topic, i) => {
      const custom = topic.challenge?.[modeKey]?.[voiceKey];
      return custom || join(voice.challenges[i], topic.challenge?.[modeKey]);
    }),
    tomo_secret_advice: [
      join(adviceLead, voice.reflection, scoreStory.advice),
      join(topics[7].action, mode.ritual, voice.question)
    ].join('\n\n')
  };
}
